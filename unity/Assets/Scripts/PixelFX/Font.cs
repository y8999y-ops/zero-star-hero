        public static readonly Dictionary<string, PixelFont> FONTS = new Dictionary<string, PixelFont>
        {
            ["mini"] = Build(MINI, 5, 2, 1),
            ["big"] = Build(BIG, 7, 3, 1),
        };

        /// 字串的寬（字型像素，還沒放大）
        public static int TextWidth(string str, string font = "mini")
        {
            var F = FONTS[font]; int w = 0;
            foreach (char ch in str) { var g = F.Find(ch); w += (g != null ? g.W : F.Space) + F.Gap; }
            return Math.Max(0, w - F.Gap);
        }
        /// 每個有墨的字型像素呼叫 plot(x, y)，字的左上角在 (0, 0)
        public static void RasterText(string str, string font, Action<int, int> plot)
        {
            var F = FONTS[font]; int x = 0;
            foreach (char ch in str)
            {
                var g = F.Find(ch);
                if (g == null) { x += F.Space + F.Gap; continue; }
                for (int r = 0; r < F.H; r++) for (int c = 0; c < g.W; c++) if (g.Rows[r][c]) plot(x + c, r);
                x += g.W + F.Gap;
            }
        }
