        static PixelFont Build(Dictionary<char, string> table, int h, int space, int gap)
        {
            var f = new PixelFont { H = h, Space = space, Gap = gap };
            foreach (var kv in table)
            {
                var rows = kv.Value.Split('|');
                if (rows.Length != h) throw new Exception("glyph " + kv.Key + " has " + rows.Length + " rows, expected " + h);
                var g = new Glyph { W = rows[0].Length, Rows = new bool[rows.Length][] };
                for (int r = 0; r < rows.Length; r++) { g.Rows[r] = new bool[rows[r].Length]; for (int c = 0; c < rows[r].Length; c++) g.Rows[r][c] = rows[r][c] == '#'; }
                f.Glyphs[kv.Key] = g;
            }
            return f;
        }

