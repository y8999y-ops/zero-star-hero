    public class Glyph { public int W; public bool[][] Rows; }
    public class PixelFont
    {
        public int H, Space, Gap;
        public Dictionary<char, Glyph> Glyphs = new Dictionary<char, Glyph>();
        /// 照 JS：先找原字，找不到再找大寫
        public Glyph Find(char ch) { if (Glyphs.TryGetValue(ch, out var g)) return g; return Glyphs.TryGetValue(char.ToUpperInvariant(ch), out g) ? g : null; }
    }

    public static class Font
